def _np():
    import numpy as np
    return np


def _cv():
    import cv2
    return cv2


def book_run(run):
    return run.repo_path(run.cfg['sources']['book_run'])


def cabin(run):
    with open(run.repo_path(run.cfg['sources']['cabin']), encoding='utf-8') as f:
        return json.load(f)


def in_pages(page, ranges):
    return any(a <= page <= b for a, b in ranges)


def is_drawing(rec):
    return 'drawing' in (rec.get('subject', '') + ' ' + rec.get('vehicle', '')).lower()


