def st_refs(run, o):
    """I0: the interior photos and drawings, each tied to the layout's panels by the names the readers wrote."""
    cat_path = os.path.join(book_run(run), 'catalogue.json')
    if not os.path.exists(cat_path):
        raise RuntimeError('no catalogue at %s: run osa_recon.py S0-S3 first' % cat_path)
    cat = json.load(open(cat_path, encoding='utf-8'))
    ranges = o.get('pages', [[82, 101]])
    aliases = run.cfg.get('panel_aliases', {})
    recs = [r for r in cat if in_pages(r['page'], ranges)]
    panels = {p['id']: [] for p in cabin(run)['panels']}
    refs = []
    for r in recs:
        text = ' '.join(str(r.get(k, '')) for k in ('subject', 'parts', 'coverage', 'view', 'vehicle_note')).lower()
        hit = sorted(pid for pid, names in aliases.items() if any(n.lower() in text for n in names))
        e = {'photo': r['photo'], 'page': r['page'], 'drawing': is_drawing(r), 'panels': hit,
             'subject': r.get('subject', ''), 'parts': r.get('parts', ''), 'coverage': r.get('coverage', '')}
        refs.append(e)
        for pid in hit:
            panels.setdefault(pid, []).append(r['photo'])
    run.write('refs.json', {'photos': refs, 'panels': panels})
    lines = ['# Interior references from the book (generated by osa_interior.py refs)', '',
             '| Panel | Photos and drawings |', '|---|---|']
    for pid in sorted(panels):
        lines.append('| `%s` | %s |' % (pid, ', '.join(panels[pid]) or '**none**'))
    lines += ['', '| Photo | Drawing | Panels | Subject | Parts |', '|---|---|---|---|---|']
    for e in refs:
        lines.append('| %s | %s | %s | %s | %s |' % (e['photo'], 'Y' if e['drawing'] else '', ', '.join(e['panels']),
                                                     e['subject'], e['parts']))
    with open(run.path('reports', 'interior_refs.md'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    covered = sum(1 for v in panels.values() if v)
    return {'outputs': ['refs.json', 'reports/interior_refs.md'],
            'metrics': {'photos': len(refs), 'drawings': sum(e['drawing'] for e in refs),
                        'panels_with_refs': covered, 'panels_without': len(panels) - covered}}


def st_calib(run, o):
    """Each interior photo's camera from its own straight edges: vanishing points, focal length, principal point,
    rotation in the cabin's axes, and one radial distortion term from the long edges."""
    import interior as I
    cv2, np = _cv(), _np()
    refs = run.read('refs.json')['photos']
    clean = os.path.join(book_run(run), 'photos', 'clean')
    out, failures, n = {}, [], 0
    for e in refs:
        if e['drawing']:
            continue
        p = os.path.join(clean, e['photo'] + '.png')
        img = cv2.imread(p)
        if img is None:
            failures.append({'photo': e['photo'], 'error': 'no clean photo'})
            continue
        n += 1
        g = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
        h, w = g.shape
        chains = I.edge_chains(g, min_len_px=max(80, w // 8))
        k1 = I.plumb_k1(chains, w, h) if len(chains) >= o.get('min_chains', 4) else 0.0
        segs = I.line_segments(g, o.get('min_seg_px', max(30, w // 40)))
        if abs(k1) > 1e-4 and len(segs):
            a = I.undistort(segs[:, :2], k1, w, h)
            b = I.undistort(segs[:, 2:], k1, w, h)
            segs = np.hstack([a, b])
        vps = I.vanishing_points(segs, n=3, thr_deg=o.get('vp_thr_deg', 1.5))
        f, pp, how = I.intrinsics_from_vps([v for v, _ in vps], w, h)
        rec = {'w': w, 'h': h, 'k1': round(k1, 4), 'segments': int(len(segs)), 'chains': len(chains), 'method': how,
               'vps': [v.tolist() for v, _ in vps], 'vp_inliers': [int(m.sum()) for _, m in vps]}
        if f:
            K = I.K_matrix(f, pp)
            rec.update({'f': round(f, 1), 'pp': [round(pp[0], 1), round(pp[1], 1)],
                        'R': I.rotation_from_vps(K, [v for v, _ in vps]).tolist()})
        out[e['photo']] = rec
    run.write('calib.json', out)
    run.item_failures('calib', failures, max(1, n + len(failures)))
    solved = sum(1 for r in out.values() if 'f' in r)
    return {'outputs': ['calib.json'], 'metrics': {'photos': n, 'calibrated': solved,
                                                   'three_vp': sum(1 for r in out.values() if r['method'].startswith('three'))}}


def face_configs(run):
    d = run.repo_path(run.cfg['sources']['faces'])
    out = []
    for p in sorted(glob.glob(os.path.join(d, '*.json'))):
        with open(p, encoding='utf-8') as f:
            c = json.load(f)
        c.setdefault('face', os.path.splitext(os.path.basename(p))[0])
        out.append(c)
    return out


def _axis_for(I, K, R, a, b):
    """The cabin axis (a column of R, signed) whose image direction at a best matches the segment a -> b."""
    np = _np()
    best = None
    for i in range(3):
        for s in (1.0, -1.0):
            d = R[:, i] * s
            x0 = np.linalg.inv(K) @ np.array([a[0], a[1], 1.0])
            p1 = K @ (x0 + 0.05 * d)
            step = p1[:2] / p1[2] - a
            seg = np.asarray(b, float) - a
            c = step @ seg / (np.linalg.norm(step) * np.linalg.norm(seg) + 1e-12)
            if best is None or c > best[0]:
                best = (c, d)
    return best[1], best[0]


def st_faces(run, o):
    """Each traced face flattened to millimetres: by the photo's own camera when it is calibrated (the aspect from
    the camera), else by its four corners onto the layout's size (and flagged: that trusts the layout)."""
    import interior as I
    cv2, np = _cv(), _np()
    calib = run.read('calib.json')
    lay = {p['id']: p for p in cabin(run)['panels']}
    clean = os.path.join(book_run(run), 'photos', 'clean')
    cfgs = face_configs(run)
    if not cfgs:
        raise StageSkipped('no face traces in %s yet (docs/OSA_INTERIOR_PIPELINE.md, "Tracing a face")' % run.cfg['sources']['faces'])
    k = o.get('px_per_mm', 4.0)
    res, failures = {}, []
    for c in cfgs:
        img = cv2.imread(os.path.join(clean, c['photo'] + '.png'))
        if img is None:
            failures.append({'face': c['face'], 'error': 'no clean photo ' + c['photo']})
            continue
        corners = np.asarray(c['corners_px'], float)  # tl, tr, br, bl in the clean photo
        refined = None
        if c.get('refine', o.get('refine', True)):
            refined = _refine_corners(run, c, corners, img.shape, o)
            if refined is not None:
                corners = refined['corners']
        panel = lay.get(c.get('panel'), {})
        known = c.get('known') or ({'width_mm': panel['size_m'][0] * 1000} if panel else None)
        if not known:
            failures.append({'face': c['face'], 'error': 'no known size and no layout panel'})
            continue
        cal = calib.get(c['photo'], {})
        method = 'camera'
        if 'f' in cal and not c.get('force_layout'):
            K = I.K_matrix(cal['f'], cal['pp'])
            R = np.array(cal['R'])
            cu = I.undistort(corners, cal.get('k1', 0.0), cal['w'], cal['h'])
            ru, qu = _axis_for(I, K, R, cu[0], cu[1])
            rv, qv = _axis_for(I, K, R, cu[0], cu[3])
            if qu < 0.98 or qv < 0.98 or abs(ru @ rv) > 0.1:
                method = 'layout'  # the face isn't on the photo's cabin axes (a tilted dash, a turned cabinet)
            else:
                H, size_mm, out_px = I.metric_rectifier(K, ru, rv, cu, known, k, o.get('margin_mm', 20))
                if cal.get('k1'):
                    # undistort the photo first so the homography applies to straight lines
                    mapx, mapy = _undistort_maps(I, cal, img.shape)
                    img = cv2.remap(img, mapx, mapy, cv2.INTER_LINEAR)
        else:
            method = 'layout'
        qa = None
        if method == 'layout' and not c.get('force_layout'):
            qa = I.quad_aspect(corners, img.shape[1], img.shape[0])
            if qa['spread'] > o.get('max_aspect_spread', 0.05) * qa['aspect']:
                qa = None
        if qa:
            # a near square-on photo: the quad's own sides give the aspect (to qa's spread), the known size the scale
            method = 'frontal'
            aspect = qa['aspect']
            W = known.get('width_mm') or known['height_mm'] * aspect
            Hh = W / aspect
            m = o.get('margin_mm', 20)
            dst = np.array([[m, m], [m + W, m], [m + W, m + Hh], [m, m + Hh]]) * k
            H = cv2.getPerspectiveTransform(corners.astype(np.float32), dst.astype(np.float32))
            size_mm, out_px = np.array([W, Hh]), (int((W + 2 * m) * k), int((Hh + 2 * m) * k))
        if method == 'layout':
            if not panel:
                failures.append({'face': c['face'], 'error': 'uncalibrated photo and no layout panel to scale by'})
                continue
            W, Hh = panel['size_m'][0] * 1000, panel['size_m'][1] * 1000
            m = o.get('margin_mm', 20)
            dst = np.array([[m, m], [m + W, m], [m + W, m + Hh], [m, m + Hh]]) * k
            H = cv2.getPerspectiveTransform(corners.astype(np.float32), dst.astype(np.float32))
            size_mm, out_px = np.array([W, Hh]), (int((W + 2 * m) * k), int((Hh + 2 * m) * k))
        face = I.rectify(img, H, out_px)
        cv2.imwrite(run.path('faces', c['face'] + '.png'), face)
        lw = panel.get('size_m', [None, None])
        res[c['face']] = {'photo': c['photo'], 'panel': c.get('panel'), 'method': method, 'px_per_mm': k,
                          'margin_mm': o.get('margin_mm', 20), 'size_mm': [round(float(x), 1) for x in size_mm],
                          'layout_mm': [round(x * 1000, 1) if x else None for x in lw]}
        if refined is not None:
            res[c['face']]['corners_px'] = [[round(float(x), 2), round(float(y), 2)] for x, y in corners]
            res[c['face']]['corner_sigma_px'] = [round(float(s), 3) for s in refined['sigma_px']]
            res[c['face']]['corners_moved_px'] = [round(float(m), 2) for m in refined['moved_px']]
            res[c['face']]['sides'] = refined['sides']
        if qa:
            res[c['face']]['aspect'] = round(qa['aspect'], 4)
            res[c['face']]['aspect_spread'] = round(qa['spread'], 4)
        if c.get('known_source'):
            res[c['face']]['known_source'] = c['known_source']
    run.write('faces.json', res)
    run.item_failures('faces', failures, len(cfgs))
    off = [abs(r['size_mm'][1] - r['layout_mm'][1]) for r in res.values()
           if r['method'] in ('camera', 'frontal') and r['layout_mm'][1]]
    return {'outputs': ['faces', 'faces.json'],
            'metrics': {'faces': len(res), 'by_camera': sum(r['method'] == 'camera' for r in res.values()),
                        'frontal': sum(r['method'] == 'frontal' for r in res.values()),
                        'height_vs_layout_mm_median': round(sorted(off)[len(off) // 2], 1) if off else None}}


def _refine_corners(run, c, corners, clean_shape, o):
    """The trace's corners measured along its sides (interior.refine_quad) on the raw crop with the screen notched out
    (interior.descreen_notch, cached in notched/), at the raw crop's full resolution; returned in the clean photo's
    pixels with each corner's sigma and how far it moved. None (the trace's corners stand) when the raw crop is
    missing or a side can't be measured. The trace's optional "edge_spans" ({side: [[x0, y0, x1, y1], ...]} in clean
    pixels) say where each side is the face's edge."""
    import interior as I
    cv2, np = _cv(), _np()
    cached = run.path('notched', c['photo'] + '.png')
    g = cv2.imread(cached, cv2.IMREAD_GRAYSCALE)
    if g is None:
        raw = cv2.imread(os.path.join(book_run(run), 'photos', 'raw', c['photo'] + '.jpg'))
        if raw is None:
            return None
        g = cv2.cvtColor(I.descreen_notch(raw)[0], cv2.COLOR_BGR2GRAY)
        cv2.imwrite(cached, g)
    s = g.shape[1] / clean_shape[1]  # raw px per clean px
    spans = {k: [[v * s for v in sp] for sp in lst] for k, lst in (c.get('edge_spans') or {}).items()}
    r = I.refine_quad(g, corners * s, spans or None, half_width=o.get('refine_half_width_px', 6.0))
    if r is None:
        return None
    C = r['corners'] / s
    return {'corners': C, 'sigma_px': r['sigma_px'] / s, 'moved_px': np.linalg.norm(C - corners, axis=1),
            'sides': r['sides']}


def _undistort_maps(I, cal, shape):
    np = _np()
    h, w = shape[:2]
    yy, xx = np.mgrid[:h, :w].astype(np.float32)
    pts = np.stack([xx.ravel(), yy.ravel()], 1).astype(float)
    d = I.distort(pts, cal['k1'], w, h)  # for each undistorted output pixel, where it was in the photo
    return d[:, 0].reshape(h, w).astype(np.float32), d[:, 1].reshape(h, w).astype(np.float32)


def st_fuse(run, o):
    """Faces of one panel from several photos merged: aligned on the sharpest, then a median."""
    import interior as I
    cv2 = _cv()
    faces = run.read('faces.json')
    by_panel = {}
    for name, r in faces.items():
        if r.get('panel'):
            by_panel.setdefault(r['panel'], []).append(name)
    out = {}
    for pid, names in by_panel.items():
        imgs = [cv2.imread(run.path('faces', n + '.png')) for n in names]
        imgs = [i for i in imgs if i is not None]
        if len(imgs) < 2:
            continue
        sharp = sorted(range(len(imgs)), key=lambda i: -cv2.Laplacian(cv2.cvtColor(imgs[i], cv2.COLOR_BGR2GRAY), cv2.CV_64F).var())
        fused, joined = I.fuse_faces([imgs[i] for i in sharp])
        cv2.imwrite(run.path('fused', pid + '.png'), fused)
        out[pid] = {'from': [names[i] for i in sharp], 'joined': joined}
    run.write('fused.json', out)
    return {'outputs': ['fused', 'fused.json'], 'metrics': {'panels_fused': len(out)}}


def _face_image(run, faces, name):
    cv2 = _cv()
    r = faces[name]
    fused = run.path('fused', (r.get('panel') or '') + '.png')
    return cv2.imread(fused if r.get('panel') and os.path.exists(fused) else run.path('faces', name + '.png'))


def st_detect(run, o):
    """Candidates for a person to accept: round parts (knobs, lamps, dial rims) by Hough circles in mm, and plate text
    by Tesseract with its Russian model when installed."""
    cv2, np = _cv(), _np()
    faces = run.read('faces.json')
    tess = run.tool('tesseract')
    # the best models live outside Program Files (tools/recon/setup_tools.ps1: tools.tessdata), else the install's own
    tdir = run.cfg.get('tools', {}).get('tessdata') or (os.path.join(os.path.dirname(tess), 'tessdata') if tess else '')
    rus = tess and os.path.exists(os.path.join(tdir, 'rus.traineddata'))
    out = {}
    for name, r in faces.items():
        img = _face_image(run, faces, name)
        if img is None:
            continue
        k = r['px_per_mm']
        g = cv2.medianBlur(cv2.cvtColor(img, cv2.COLOR_BGR2GRAY), 5)
        c = cv2.HoughCircles(g, cv2.HOUGH_GRADIENT, 1.2, minDist=int(8 * k), param1=120, param2=o.get('circle_votes', 28),
                             minRadius=int(o.get('min_r_mm', 3) * k), maxRadius=int(o.get('max_r_mm', 45) * k))
        circles = [] if c is None else [[round(float(x) / k - r['margin_mm'], 1), round(float(y) / k - r['margin_mm'], 1), round(float(rr) / k, 1)]
                                        for x, y, rr in c[0]]
        out[name] = {'circles_mm': circles}
        if rus:
            p = run.path('detect', name + '.png')
            cv2.imwrite(p, cv2.resize(img, None, fx=2, fy=2, interpolation=cv2.INTER_CUBIC))
            txt = run.path('detect', name)
            try:
                run.call([tess, p, txt, '--tessdata-dir', tdir, '-l', 'rus+eng', '--psm', '11', 'tsv'], 300, 'detect')
                out[name]['ocr_tsv'] = os.path.relpath(txt + '.tsv', run.dir)
            except RuntimeError as e:
                out[name]['ocr_error'] = str(e)[:200]
    run.write('candidates.json', out)
    note = '' if rus else 'no OCR: Tesseract\'s rus.traineddata is not installed (tessdata_best rus)'
    return {'outputs': ['candidates.json'], 'note': note,
            'metrics': {'faces': len(out), 'circles': sum(len(v['circles_mm']) for v in out.values()), 'ocr': bool(rus)}}


def st_room(run, o):
    """Each wide photo's camera from named panel corners (PnP), and how far the layout is from it at each corner."""
    import interior as I
    kp_path = run.repo_path(run.cfg['sources']['keypoints'])
    if not os.path.exists(kp_path):
        raise StageSkipped('no keypoints file %s (named panel corners per photo)' % run.cfg['sources']['keypoints'])
    kps = json.load(open(kp_path, encoding='utf-8'))
    calib = run.read('calib.json')
    pts3 = I.cabin_points(cabin(run))
    out, failures = {}, []
    for photo, pts in kps.items():
        cal = calib.get(photo, {})
        w, h = cal.get('w'), cal.get('h')
        if not w:
            img = _cv().imread(os.path.join(book_run(run), 'photos', 'clean', photo + '.png'))
            if img is None:
                failures.append({'photo': photo, 'error': 'no photo'})
                continue
            h, w = img.shape[:2]
        r = I.room_pose(pts, pts3, w, h)
        if r is None:
            failures.append({'photo': photo, 'error': 'fewer than 6 known points'})
            continue
        out[photo] = r
    run.write('room.json', out)
    run.item_failures('room', failures, max(1, len(kps)))
    worst = sorted(((v['mm'], p + ':' + k) for p, r in out.items() for k, v in r['points'].items()), reverse=True)[:5]
    return {'outputs': ['room.json'], 'metrics': {'photos': len(out), 'worst_mm': worst}}


def st_verify(run, o):
    """The layout's items (controls, lamps, displays, fixtures) laid on each flattened face; each item's distance to
    the nearest round part found there. A large offset is the data's error or a part the photo doesn't show; either
    way a person looks at the overlay."""
    cv2, np = _cv(), _np()
    faces = run.read('faces.json')
    cand = run.read('candidates.json') if os.path.exists(run.path('candidates.json')) else {}
    lay = cabin(run)
    items = {}
    for key in ('controls', 'lamps', 'displays', 'fixtures'):
        for it in lay.get(key, []):
            if 'panel' in it and 'at_m' in it:
                items.setdefault(it['panel'], []).append((it.get('control') or it.get('id') or it.get('kind', key), it['at_m']))
    report = {}
    for name, r in faces.items():
        pid = r.get('panel')
        img = _face_image(run, faces, name)
        if img is None or pid not in items:
            continue
        k, m = r['px_per_mm'], r['margin_mm']
        W, H = r['size_mm']
        circ = np.array([c[:2] for c in cand.get(name, {}).get('circles_mm', [])]) if cand.get(name, {}).get('circles_mm') else np.zeros((0, 2))
        offs = []
        over = img.copy()
        lw = int(max(2, 1.2 * k))
        to_px = lambda x, y: (int((x + m) * k), int((y + m) * k))
        lay_w, lay_h = r.get('layout_mm') or (None, None)
        if lay_w and lay_h:  # the layout's outline about the face's centre: blue, so a wrong size shows at a glance
            cv2.rectangle(over, to_px(W / 2 - lay_w / 2, H / 2 - lay_h / 2), to_px(W / 2 + lay_w / 2, H / 2 + lay_h / 2), (255, 80, 0), lw * 2)
        for x, y, rr in cand.get(name, {}).get('circles_mm', []):  # the parts found: green
            cv2.circle(over, to_px(x, y), int(rr * k), (0, 200, 0), lw)
        for label, (u, v) in items[pid]:
            x, y = W / 2 + u * 1000, H / 2 - v * 1000  # at_m: u right, v up from the panel's centre
            cv2.drawMarker(over, to_px(x, y), (0, 0, 255), cv2.MARKER_CROSS, int(20 * k), lw)  # the layout's items: red
            if len(circ):
                d = float(np.min(np.hypot(circ[:, 0] - x, circ[:, 1] - y)))
                if d < o.get('match_mm', 25):
                    offs.append(d)
        cv2.imwrite(run.path('verify', name + '.jpg'), over, [cv2.IMWRITE_JPEG_QUALITY, 90])
        report[name] = {'items': len(items[pid]), 'matched': len(offs),
                        'median_offset_mm': round(float(np.median(offs)), 1) if offs else None}
    run.write(os.path.join('reports', 'verify.json'), report)
    return {'outputs': ['verify', 'reports/verify.json'], 'metrics': {'faces': len(report)}}


def st_build(run, o):
    """The existing tools rebuild the cabin from the layout: baked panel faces, then the Blender meshes."""
    if not o.get('enabled'):
        raise StageSkipped('the traces go into data/cabins/osa_ak.json by a person first; set stages.build.enabled')
    blender = run.tool('blender')
    run.call([sys.executable, os.path.join(REPO, 'tools', 'cabin_textures.py'), '--only', 'panels'], o.get('timeout_s', 1800), 'build')
    if not blender:
        raise StageSkipped('textures baked; Blender not found for the meshes')
    run.call([blender, '--background', '--python', os.path.join(REPO, 'tools', 'blender', 'build_cabin_interior.py')],
             o.get('timeout_s', 1800), 'build')
    return {'outputs': [], 'metrics': {}}


STAGES = [
    Stage('refs', st_refs, title='I0 the panels\' photos and drawings'),
    Stage('calib', st_calib, deps=('refs',), title='each photo\'s camera from the cabin\'s straight edges'),
    Stage('faces', st_faces, deps=('calib',), optional=True, title='traced faces flattened to millimetres'),
    Stage('fuse', st_fuse, deps=('faces',), optional=True, title='views of one face merged'),
    Stage('detect', st_detect, deps=('faces',), optional=True, title='round parts and plate text as candidates'),
    Stage('room', st_room, deps=('calib',), optional=True, title='wide photos\' cameras from panel corners'),
    Stage('verify', st_verify, deps=('faces', 'detect'), optional=True, title='the layout laid on the faces'),
    Stage('build', st_build, deps=('verify',), optional=True, title='textures and meshes rebuilt'),
]


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('cmd', choices=['run', 'status', 'list'])
    ap.add_argument('config')
    ap.add_argument('--only', default='')
    ap.add_argument('--force', default='')
    a = ap.parse_args(argv)
    run = Run(a.config)
    if a.cmd == 'list':
        for s in STAGES:
            print('%-8s %s%s' % (s.name, s.title, ' (optional)' if s.optional else ''))
        return 0
    if a.cmd == 'status':
        for s in STAGES:
            r = run.manifest.get(s.name, {})
            print('%-8s %-8s %s %s' % (s.name, r.get('status', '-'), json.dumps(r.get('metrics', {}), ensure_ascii=False)[:120], r.get('note', '')[:100]))
        return 0
    only = set(x for x in a.only.split(',') if x) or None
    force = set(x for x in a.force.split(',') if x)
    return 0 if execute(run, STAGES, only, force) else 1


if __name__ == '__main__':
    sys.exit(main())
