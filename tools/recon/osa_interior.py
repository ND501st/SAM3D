"""Interior pipeline: the book's cabin photographs and drawings -> measured faces, positions and checks for the 9A33BM2's
compartment (docs/OSA_INTERIOR_PIPELINE.md; roadmap docs/OSA_MODEL_ROADMAP.md I0-I8).

It runs on the exterior run's cut and descreened photos (`sources.book_run`: S0-S3 of osa_recon.py) and on the cabin
layout (`data/cabins/osa_ak.json`), with the same framework: resume, retries, per-photo isolation, optional stages
that skip with their reason.

    python tools/recon/osa_interior.py run    tools/recon/osa_interior.json
    python tools/recon/osa_interior.py status tools/recon/osa_interior.json
    python tools/recon/osa_interior.py list   tools/recon/osa_interior.json

Stages: refs (I0: every panel's photos and drawings), calib (each photo's focal length, principal point, rotation and
lens distortion from the cabin's straight edges), faces (each traced face flattened to millimetres with the right
aspect), fuse (several views of one face merged), detect (round parts and, with a Cyrillic OCR, plates as candidates
for a person), room (each wide photo's camera from named panel corners, and the layout's error at each corner),
verify (the layout's controls laid on the flattened faces: how far the data is from the photograph), build (the
existing Blender and texture tools, once the traces are in the layout).
"""
